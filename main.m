% 设置参数
q = 2;                    % GF(2)
g = [1, 1, 1];           % x^2 + x + 1
v = 2;                    % 矩阵维度
m = 2;                    % 输出矩阵列数

% 创建多项式矩阵 A (v×v)
A = cell(2, 2);
A{1,1} = [1, 0, 1];      % x^2 + 1
A{1,2} = [0, 1];         % x
A{2,1} = [1, 1];         % x + 1
A{2,2} = [1];            % 1

% 创建多项式矩阵 B (v×m)
B = cell(2, 2);
B{1,1} = [1, 1];         % x + 1
B{1,2} = [0, 1];         % x
B{2,1} = [1];            % 1
B{2,2} = [1, 0, 1];      % x^2 + 1

% 计算矩阵乘法
C = poly_matrix_mult_mod(A, B, g, q);

% 显示结果
fprintf('结果矩阵 C (%d×%d):\n', v, m);
for i = 1:v
    for j = 1:m
        fprintf('C{%d,%d} = ', i, j);
        disp(C{i,j});
    end
end

